-- Ручная правка времени участника. Время считается из отметок судьи, но судья
-- бежит рядом с ребёнком и кнопку иногда жмёт поздно — или не жмёт вовсе.
-- Тогда админ вписывает чистое время руками, а посчитанное остаётся в отметках
-- нетронутым: пустое поле возвращает всё как было.
--
-- Хранится чистое время, без штрафов: штрафы добавляются к нему так же, как к
-- посчитанному, иначе правка времени тихо отменяла бы штраф.
ALTER TABLE festival_participant
  ADD COLUMN IF NOT EXISTS time_override_seconds INTEGER
  CHECK (time_override_seconds IS NULL OR time_override_seconds >= 0);
