-- Награда праздника открывается ребёнком: «Твои искры за Спарту» → нажал →
-- число. До нажатия сумма не уходит на клиент, как и в сундуке розыгрыша.
--
-- Начисление привязано к открытию, а не к публикации: карточка и есть вручение.
ALTER TABLE event_award
  ADD COLUMN IF NOT EXISTS opened_at TIMESTAMP WITH TIME ZONE;

-- Идёт ли награда в общий рейтинг лагеря. Искры за события дня рождения
-- (Спарта, Путь воина) считаются только внутри праздника: они уже про этот
-- день, и тащить их в общий зачёт смен незачем.
ALTER TABLE event_award
  ADD COLUMN IF NOT EXISTS in_rating BOOLEAN NOT NULL DEFAULT TRUE;
