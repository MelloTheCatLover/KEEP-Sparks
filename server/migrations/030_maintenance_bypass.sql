-- Пропуск на техобслуживание. Иногда сайт нужно оставить открытым конкретному
-- ребёнку, пока он закрыт для остальных (проверить правку на живом аккаунте,
-- показать смену). Делать ради этого админом нельзя — админка даёт ПДн всех
-- детей, а пропуск не даёт ничего сверх обычного входа.
--
-- Флаг на пользователе, а не список в app_state: снимается вместе с аккаунтом
-- и виден там же, где остальные признаки ребёнка.
ALTER TABLE user_main
  ADD COLUMN IF NOT EXISTS maintenance_bypass BOOLEAN NOT NULL DEFAULT FALSE;
