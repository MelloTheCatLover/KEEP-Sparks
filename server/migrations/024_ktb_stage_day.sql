-- Этап КТБ привязывается ко дню смены. Раньше искры за этап ложились на
-- последний день смены и открывались ребёнку только вместе с ним — этап,
-- подведённый на третий день, ждал разъезда. Теперь админ говорит, в какой день
-- этап прошёл, и искры за него уходят вместе с этим днём.
--
-- NULL = последний день смены: так ведут себя все этапы, заведённые до этой
-- миграции, и так же новый этап, если админ день не выбрал.
ALTER TABLE ktb_stage
  ADD COLUMN IF NOT EXISTS day_number INTEGER;
