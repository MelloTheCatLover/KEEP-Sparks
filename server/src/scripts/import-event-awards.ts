// Ё и е в базе встречаются вперемешку («Глёх», «Фёдор»), регистр тоже — ключ
// нормализуется, иначе половина строк не находится.
function key(s: string): string {
  return s.toLowerCase().replace(/ё/g, "е").replace(/\s+/g, " ").trim();
}

async function main(): Promise<void> {
  const apply = process.argv.includes("--apply");

  const { rows: roster } = await pool.query<{ user_id: string; fio: string }>(
    `SELECT m.user_id,
            (u.l_name || ' ' || u.f_name || ' ' || COALESCE(u.m_name, '')) AS fio
     FROM shift_members m
     JOIN user_main u ON u.id = m.user_id
     WHERE m.shift_id = $1`,
    [SHIFT_ID],
  );

  // Текущие итоги всех детей одним запросом: колонка «искры до смены» из
  // таблицы должна совпасть с ними. Расходится — значит строка легла не на того
  // человека (тёзки), и это надо увидеть до записи.
  const totals = new Map(
    (await getRanking()).map((r) => [r.user_id, r.sparks]),
  );

  const byName = new Map<string, string>();
  const dupes = new Set<string>();
  for (const r of roster) {
    const k = key(r.fio);
    if (byName.has(k)) dupes.add(k);
    byName.set(k, r.user_id);
  }

  type Award = { userId: string; title: string; amount: number };
  const awards: Award[] = [];
  const missing: string[] = [];
  const mismatched: string[] = [];

  for (const line of ROWS.split("\n")) {
    const [fio, before, sparta, warrior] = line.split("|");
    const userId = byName.get(key(fio));
    if (!userId) {
      missing.push(fio);
      continue;
    }
    if (dupes.has(key(fio))) mismatched.push(`${fio}: тёзки в ростере`);

    const now = totals.get(userId);
    if (now !== undefined && now !== Number(before)) {
      mismatched.push(`${fio}: в таблице ${before}, в базе ${now}`);
    }

    if (Number(sparta) !== 0) {
      awards.push({ userId, title: "Спарта", amount: Number(sparta) });
    }
    if (Number(warrior) !== 0) {
      awards.push({ userId, title: "Путь воина", amount: Number(warrior) });
    }
  }

  console.log(`строк в таблице: ${ROWS.split("\n").length}`);
  console.log(`наград к выдаче: ${awards.length}`);
  if (missing.length) {
    console.log(`НЕ НАЙДЕНЫ в ростере смены ${SHIFT_ID} (${missing.length}):`);
    for (const m of missing) console.log("  " + m);
  }
  if (mismatched.length) {
    console.log("предупреждения:");
    for (const m of mismatched) console.log("  " + m);
  }

  if (!apply) {
    console.log("\nсухой прогон, ничего не записано. Повторить с --apply");
    await pool.end();
    return;
  }

  // Идемпотентность: свои строки переписываются целиком, чужие награды
  // праздника не трогаются.
  await pool.query(
    `DELETE FROM event_award
     WHERE shift_id = $1 AND title IN ('Спарта', 'Путь воина')`,
    [SHIFT_ID],
  );
  await pool.query(
    `INSERT INTO event_award
       (shift_id, user_id, title, amount, published_at, in_rating)
     SELECT $1, u, t, a, NOW(), FALSE
     FROM unnest($2::uuid[], $3::text[], $4::int[]) AS x(u, t, a)`,
    [
      SHIFT_ID,
      awards.map((a) => a.userId),
      awards.map((a) => a.title),
      awards.map((a) => a.amount),
    ],
  );
  console.log(`записано наград: ${awards.length}`);
  await pool.end();
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
