// Ё и е в базе встречаются вперемешку («Глёх», «Фёдор»), регистр тоже — ключ
// нормализуется, иначе половина строк не находится.
function key(s: string): string {
  return s.toLowerCase().replace(/ё/g, "е").replace(/\s+/g, " ").trim();
}

async function main(): Promise<void> {
  const apply = process.argv.includes("--apply");

  const { rows: roster } = await pool.query<{ user_id: string; fio: string }>(
    `SELECT m.user_id,
            (u.l_name || ' ' || u.f_name || ' ' || COALESCE(u.m_name, '')) AS fio
     FROM shift_members m
     JOIN user_main u ON u.id = m.user_id
     WHERE m.shift_id = $1`,
    [SHIFT_ID],
  );

  // Текущие итоги всех детей одним запросом: колонка «искры до смены» из
  // таблицы сверяется с ними. Числа расходятся на вклад раскрытых дней идущей
  // смены — это нормально; важно, что расхождение небольшое, иначе строка
  // легла не на того человека.
  const totals = new Map((await getRanking()).map((r) => [r.user_id, r.sparks]));

  const byName = new Map<string, string>();
  const dupes = new Set<string>();
  for (const r of roster) {
    const k = key(r.fio);
    if (byName.has(k)) dupes.add(k);
    byName.set(k, r.user_id);
  }

  // Что уже выдано: (кто + за что) -> текущая сумма и открыта ли карточка.
  const { rows: existing } = await pool.query<{
    id: number;
    user_id: string;
    title: string;
    amount: number;
    opened: boolean;
  }>(
    `SELECT id::int, user_id, title, amount, (opened_at IS NOT NULL) AS opened
     FROM event_award WHERE shift_id = $1 AND title = ANY($2::text[])`,
    [SHIFT_ID, [...COLUMNS]],
  );
  const have = new Map(existing.map((e) => [`${e.user_id}|${e.title}`, e]));

  const toInsert: { userId: string; title: string; amount: number }[] = [];
  const toUpdate: { id: number; amount: number; note: string }[] = [];
  const missing: string[] = [];
  const warnings: string[] = [];

  for (const line of ROWS.split("\n")) {
    const [fio, before, total, ...values] = line.split("|");

    // Сумма столбцов должна сойтись с ИТОГО — ловит опечатку в переносе.
    const sum = values.reduce((s, v) => s + Number(v), 0);
    if (sum !== Number(total)) {
      warnings.push(`${fio}: столбцы дают ${sum}, в ИТОГО ${total}`);
    }

    const userId = byName.get(key(fio));
    if (!userId) {
      missing.push(fio);
      continue;
    }
    if (dupes.has(key(fio))) warnings.push(`${fio}: тёзки в ростере`);

    const now = totals.get(userId);
    if (now !== undefined && Math.abs(now - Number(before)) > 1000) {
      warnings.push(`${fio}: в таблице ${before}, в базе ${now} — сверь ФИО`);
    }

    COLUMNS.forEach((title, i) => {
      const amount = Number(values[i]);
      const row = have.get(`${userId}|${title}`);
      if (amount === 0) {
        if (row) warnings.push(`${fio}: «${title}» выдана, но в таблице 0`);
        return;
      }
      if (!row) {
        toInsert.push({ userId, title, amount });
      } else if (row.amount !== amount) {
        toUpdate.push({
          id: row.id,
          amount,
          note: `${fio}: «${title}» ${row.amount} → ${amount}${row.opened ? " (уже открыта)" : ""}`,
        });
      }
    });
  }

  console.log(`строк в таблице: ${ROWS.split("\n").length}`);
  console.log(`новых наград: ${toInsert.length}, правок сумм: ${toUpdate.length}`);
  for (const u of toUpdate) console.log("  " + u.note);
  if (missing.length) {
    console.log(`НЕ НАЙДЕНЫ в ростере смены ${SHIFT_ID} (${missing.length}):`);
    for (const m of missing) console.log("  " + m);
  }
  if (warnings.length) {
    console.log("предупреждения:");
    for (const w of warnings) console.log("  " + w);
  }

  if (!apply) {
    console.log("\nсухой прогон, ничего не записано. Повторить с --apply");
    await pool.end();
    return;
  }

  if (toInsert.length > 0) {
    await pool.query(
      `INSERT INTO event_award
         (shift_id, user_id, title, amount, published_at, in_rating)
       SELECT $1, u, t, a, NOW(), FALSE
       FROM unnest($2::uuid[], $3::text[], $4::int[]) AS x(u, t, a)`,
      [
        SHIFT_ID,
        toInsert.map((a) => a.userId),
        toInsert.map((a) => a.title),
        toInsert.map((a) => a.amount),
      ],
    );
  }
  for (const u of toUpdate) {
    await pool.query("UPDATE event_award SET amount = $2 WHERE id = $1", [
      u.id,
      u.amount,
    ]);
  }
  console.log(`записано: ${toInsert.length} новых, ${toUpdate.length} правок`);
  await pool.end();
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
