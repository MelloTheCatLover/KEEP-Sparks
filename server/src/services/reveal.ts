import { env } from "../config/env";

// Раскрытие искр ведущейся смены. День открывается ребёнку ровно тогда, когда
// админ нажал «отдать искры» (`shift_day.ready_at`), и закрывается обратно,
// когда он флаг снял. Часа раскрытия больше нет: полдень следующего дня плохо
// ложился на реальный распорядок — итоги подводят когда получится, а показать
// их иногда нужно сразу.
//
// Фильтр применяется на сервере, а не в UI: дети открывают инструменты
// разработчика.

// Таймзона попадает прямо в SQL-литерал, поэтому пропускаем только то, из чего
// состоят имена зон в базе IANA.
const SAFE_TZ = /^[A-Za-z0-9/_+-]+$/;

// Таймзона лагеря. Нужна раскрытию составов КТБ: там админ вводит «настенное»
// время, и его надо разобрать в момент.
export function timezone(): string {
  const tz = env.sparks.timezone;
  if (!SAFE_TZ.test(tz)) {
    throw new Error(`Bad SPARKS_TIMEZONE: ${tz}`);
  }
  return tz;
}

// Предикат «этот день уже отдан ребёнку».
export function revealedSql(readyAt: string): string {
  return `${readyAt} IS NOT NULL`;
}
